import {readFile,writeFile,mkdir,readdir,unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import sharp from 'sharp';

const manifest=JSON.parse(await readFile('docs/ASSET_MANIFEST.json','utf8'));
const directory='public/art/runtime';await mkdir(directory,{recursive:true});
const assets={};let original=0,optimized=0;
for(const asset of Object.values(manifest.assets)){
 if(asset.kind==='reference')continue;
 const input=await readFile(`public${asset.path}`);original+=input.length;
 const background=asset.kind==='background';
 const widths=background?[1440,960]:[asset.width];const variants=[];
 for(const width of widths){
  const buffer=await sharp(input).resize({width,withoutEnlargement:true}).webp({quality:background?74:78,alphaQuality:95,effort:6}).toBuffer();
  const hash=createHash('sha256').update(buffer).digest('hex').slice(0,10);
  const filename=`${asset.id}-${width}.${hash}.webp`;await writeFile(`${directory}/${filename}`,buffer);
  variants.push({src:`/art/runtime/${filename}`,width,bytes:buffer.length});
 }
 const placeholder=background?`data:image/webp;base64,${(await sharp(input).resize({width:48}).webp({quality:35}).toBuffer()).toString('base64')}`:undefined;
 assets[asset.path]={...variants[0],height:Math.round(asset.height*variants[0].width/asset.width),small:variants[1],placeholder};
 optimized+=variants[0].bytes;
}
await writeFile('lib/game/assets.generated.ts',`// Generated by scripts/optimize-art.mjs; original paintings remain in public/art.\nexport const ASSETS = ${JSON.stringify(assets,null,2)} as const;\n`);
const keep=new Set(Object.values(assets).flatMap(a=>[a.src.split('/').at(-1),a.small?.src.split('/').at(-1)]).filter(Boolean));
for(const file of await readdir(directory)){if(!keep.has(file))await unlink(`${directory}/${file}`);}
await writeFile('docs/ART_PERFORMANCE.json',JSON.stringify({originalBytes:original,runtimeBytes:optimized,reduction:1-optimized/original,assets},null,2)+'\n');
console.log(JSON.stringify({originalBytes:original,runtimeBytes:optimized,reduction:`${Math.round((1-optimized/original)*100)}%`}));
